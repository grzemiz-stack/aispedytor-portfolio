--
-- Kolumna miala dwie sprzeczne semantyki zapisywane przez dwie rozne sciezki:
--   searchOffers                 -> nadpisywala ja migawka z ostatniego wyszukiwania
--   checkNewOfferAgainstDemands  -> inkrementowala ja kumulatywnie
